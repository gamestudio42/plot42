export function formatMoney(value: number): string {
  const sign = value < 0 ? '−' : '';
  return `${sign}$${Math.abs(Math.round(value)).toLocaleString('pt-BR')}`;
}

export function formatNumber(value: number): string {
  return Math.round(value).toLocaleString('pt-BR');
}

